class _DayButton extends StatelessWidget {
  const _DayButton({
    required this.date,
    required this.doseCount,
    required this.selected,
    required this.isToday,
    required this.onTap,
  });

  final DateTime date;
  final int doseCount;
  final bool selected;
  final bool isToday;
  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    return Semantics(
      button: true,
      selected: selected,
      label:
          '${MaterialLocalizations.of(context).formatFullDate(date)}, ${context.protocolL10n.plannerScheduledCount(doseCount)}',
      child: GestureDetector(
        onTap: onTap,
        child: AnimatedContainer(
          duration: AppDurations.fast,
          margin: const EdgeInsets.symmetric(horizontal: 2),
          padding: const EdgeInsets.symmetric(vertical: AppSpacing.sm),
          decoration: BoxDecoration(
            color: selected ? AppColors.primaryFaint : Colors.transparent,
            borderRadius: BorderRadius.circular(AppSpacing.buttonRadius),
            border: Border.all(
              color: selected
                  ? AppColors.primary
                  : isToday
                  ? AppColors.borderCyan
                  : AppColors.border,
            ),
          ),
          child: Column(
            children: [
              Text(
                MaterialLocalizations.of(
                  context,
                ).narrowWeekdays[date.weekday % 7].toUpperCase(),
                style: AppTypography.labelSmall.copyWith(
                  color: selected ? AppColors.primary : AppColors.textSecondary,
                  letterSpacing: 0.4,
                ),
              ),
              const SizedBox(height: AppSpacing.xs),
              Text(
                '${date.day}',
                style: AppTypography.tabular.copyWith(fontSize: 16),
              ),
              const SizedBox(height: AppSpacing.xs),
              Container(
                width: doseCount > 0 ? 6 : 3,
                height: doseCount > 0 ? 6 : 3,
                decoration: BoxDecoration(
                  color: doseCount > 0
                      ? AppColors.primary
                      : AppColors.textDisabled,
                  shape: BoxShape.circle,
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}

