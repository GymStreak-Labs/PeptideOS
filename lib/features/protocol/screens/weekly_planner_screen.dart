class _PlannerItem {
  const _PlannerItem({
    required this.protocol,
    required this.peptide,
    required this.schedule,
    required this.time,
    required this.phase,
    required this.colorHex,
    required this.scheduledAt,
    required this.doseLog,
  });

  final Protocol protocol;
  final ProtocolPeptide peptide;
  final ProtocolDoseSchedule schedule;
  final String time;
  final ProtocolPhase? phase;
  final String colorHex;
  final DateTime? scheduledAt;
  final DoseLog? doseLog;

  bool get canOpen =>
      doseLog != null ||
      (scheduledAt != null && !scheduledAt!.isAfter(DateTime.now()));

  String? statusLabel(BuildContext context) {
    final dose = doseLog;
    if (dose?.isTaken == true) return context.protocolL10n.plannerTaken;
    if (dose?.skipped == true) return context.protocolL10n.protocolSkipped;
    if (dose?.isMissed(DateTime.now()) == true) {
      return context.protocolL10n.protocolMissed;
    }
    if (dose == null && canOpen) return context.protocolL10n.protocolLogDose;
    return null;
  }

  Color get statusColor {
    if (doseLog?.isTaken == true) return AppColors.success;
    if (doseLog?.skipped == true) return AppColors.textSecondary;
    if (doseLog?.isMissed(DateTime.now()) == true) return AppColors.warning;
    return AppColors.primary;
  }
}

class _WashoutItem {
  const _WashoutItem({
    required this.protocol,
    required this.peptide,
    required this.colorHex,
  });

  final Protocol protocol;
  final ProtocolPeptide peptide;
  final String colorHex;
}

DateTime _day(DateTime value) => DateTime(value.year, value.month, value.day);

DateTime _mondayOf(DateTime value) =>
    _day(value).subtract(Duration(days: value.weekday - DateTime.monday));

bool _sameDay(DateTime a, DateTime b) =>
    a.year == b.year && a.month == b.month && a.day == b.day;

String _amount(BuildContext context, double value) => NumberFormat(
  value == value.roundToDouble() ? '0' : '0.##',
  context.protocolL10n.localeName,
).format(value);

String _localizedStoredTime(BuildContext context, String value) {
  final parts = value.split(':');
  final hour = parts.isNotEmpty ? int.tryParse(parts.first) : null;
  final minute = parts.length > 1 ? int.tryParse(parts[1]) : null;
  if (hour == null || minute == null) return value;
  return TimeOfDay(hour: hour, minute: minute).format(context);
}

DateTime? _scheduledAt(DateTime date, String value) {
  final parts = value.split(':');
  if (parts.length != 2) return null;
  final hour = int.tryParse(parts[0]);
  final minute = int.tryParse(parts[1]);
  if (hour == null || minute == null) return null;
  return DateTime(date.year, date.month, date.day, hour, minute);
}

String _weekRangeLabel(BuildContext context, DateTime monday) {
  final sunday = monday.add(const Duration(days: 6));
  final material = MaterialLocalizations.of(context);
  return '${material.formatShortDate(monday)} – ${material.formatShortDate(sunday)}';
}
