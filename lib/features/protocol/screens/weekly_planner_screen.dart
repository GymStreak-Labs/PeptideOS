/// A read-only calendar generated from the user's saved protocol schedules.
///
/// The planner intentionally delegates all schedule decisions to
/// [ProtocolPeptide.scheduleForDate] so it can never drift from the dose logs
/// and reminders generated by [ProtocolProvider].
class WeeklyPlannerScreen extends StatefulWidget {
  const WeeklyPlannerScreen({
    super.key,
    required this.protocols,
    this.doseLogs = const [],
    this.initialDate,
  });

  final List<Protocol> protocols;
  final List<DoseLog> doseLogs;
  final DateTime? initialDate;

  @override
  State<WeeklyPlannerScreen> createState() => _WeeklyPlannerScreenState();
}

class _WeeklyPlannerScreenState extends State<WeeklyPlannerScreen> {
  static const _uuid = Uuid();
  late DateTime _selectedDate;
  late DateTime _weekStart;
  late List<DoseLog> _doseLogs;

  @override
  void initState() {
    super.initState();
    _selectedDate = _day(widget.initialDate ?? DateTime.now());
    _weekStart = _mondayOf(_selectedDate);
    _doseLogs = List<DoseLog>.from(widget.doseLogs);
  }

  @override
  void didUpdateWidget(covariant WeeklyPlannerScreen oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (!identical(oldWidget.doseLogs, widget.doseLogs)) {
      _doseLogs = List<DoseLog>.from(widget.doseLogs);
    }
  }

  @override
  Widget build(BuildContext context) {
    final days = List<DateTime>.generate(
      7,
      (index) => _weekStart.add(Duration(days: index)),
    );
    final selectedItems = _itemsForDate(_selectedDate);
    final selectedWashouts = _washoutsForDate(_selectedDate);

    return Scaffold(
      backgroundColor: AppColors.background,
      body: SafeArea(
        child: Column(
          children: [
            _PlannerHeader(
              rangeLabel: _weekRangeLabel(context, _weekStart),
              onBack: () => Navigator.of(context).pop(),
              onPrevious: () => _moveWeek(-1),
              onNext: () => _moveWeek(1),
            ),
            Padding(
              padding: const EdgeInsets.fromLTRB(
                AppSpacing.screenHorizontal,
                AppSpacing.base,
                AppSpacing.screenHorizontal,
                AppSpacing.sm,
              ),
              child: Row(
                children: [
                  Text('SCHEDULE // 7 DAYS', style: AppTypography.systemLabel),
                  const Spacer(),
                  GestureDetector(
                    onTap: _jumpToToday,
                    child: Text(
                      context.protocolL10n.plannerToday,
                      style: AppTypography.systemLabel.copyWith(
                        color: AppColors.textSecondary,
                      ),
                    ),
                  ),
                ],
              ),
            ),
            Padding(
              padding: const EdgeInsets.symmetric(
                horizontal: AppSpacing.screenHorizontal,
              ),
              child: Row(
                children: [
                  for (final date in days)
                    Expanded(
                      child: _DayButton(
                        date: date,
                        doseCount: _itemsForDate(date).length,
                        selected: _sameDay(date, _selectedDate),
                        isToday: _sameDay(date, DateTime.now()),
                        onTap: () {
                          HapticFeedback.selectionClick();
                          setState(() => _selectedDate = date);
                        },
                      ),
                    ),
                ],
              ),
            ),
            const SizedBox(height: AppSpacing.lg),
            Expanded(
              child: ListView(
                padding: const EdgeInsets.fromLTRB(
                  AppSpacing.screenHorizontal,
                  0,
                  AppSpacing.screenHorizontal,
                  AppSpacing.screenBottom,
                ),
                children: [
                  Text(
                    MaterialLocalizations.of(
                      context,
                    ).formatFullDate(_selectedDate).toUpperCase(),
                    style: AppTypography.systemLabel.copyWith(
                      color: AppColors.textSecondary,
                    ),
                  ),
                  const SizedBox(height: AppSpacing.sm),
                  if (selectedItems.isEmpty && selectedWashouts.isEmpty)
                    const _EmptyDayCard()
                  else ...[
                    for (final item in selectedItems) ...[
                      _PlannedDoseCard(
                        item: item,
                        onTap: item.canOpen ? () => _openDose(item) : null,
                      ),
                      const SizedBox(height: AppSpacing.cardGap),
                    ],
                    for (final item in selectedWashouts) ...[
                      _WashoutCard(item: item),
                      const SizedBox(height: AppSpacing.cardGap),
                    ],
                  ],
                  const SizedBox(height: AppSpacing.sm),
                  Text(
                    context.protocolL10n.plannerTrackingDisclaimer,
                    style: AppTypography.disclaimer.copyWith(
                      color: AppColors.textSecondary,
                    ),
                  ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }

  List<_PlannerItem> _itemsForDate(DateTime date) {
    final result = <_PlannerItem>[];
    for (final protocol in widget.protocols) {
      if (protocol.status != ProtocolStatus.active ||
          date.isBefore(_day(protocol.startDate))) {
        continue;
      }
      if (protocol.endDate != null && date.isAfter(_day(protocol.endDate!))) {
        continue;
      }
      for (var index = 0; index < protocol.peptides.length; index++) {
        final peptide = protocol.peptides[index];
        final schedule = peptide.scheduleForDate(
          protocolStart: protocol.startDate,
          date: date,
        );
        if (schedule == null) continue;
        final phase = peptide.phaseForDate(
          protocolStart: protocol.startDate,
          date: date,
        );
        for (final time in schedule.scheduledTimes) {
          final scheduledAt = _scheduledAt(date, time);
          final doseLog = scheduledAt == null
              ? null
              : _matchingDoseLog(protocol.uuid, peptide.uuid, scheduledAt);
          result.add(
            _PlannerItem(
              protocol: protocol,
              peptide: peptide,
              schedule: schedule,
              time: time,
              phase: phase,
              colorHex: peptide.labelColorHex.isEmpty
                  ? defaultPeptideLabelColorHex(index)
                  : peptide.labelColorHex,
              scheduledAt: scheduledAt,
              doseLog: doseLog,
            ),
          );
        }
      }
    }
    result.sort((a, b) => a.time.compareTo(b.time));
    return result;
  }

  DoseLog? _matchingDoseLog(
    String protocolUuid,
    String peptideUuid,
    DateTime scheduledAt,
  ) {
    for (final dose in _doseLogs) {
      if (dose.protocolUuid == protocolUuid &&
          dose.protocolPeptideUuid == peptideUuid &&
          dose.scheduledAt.isAtSameMomentAs(scheduledAt)) {
        return dose;
      }
    }
    return null;
  }

  Future<void> _openDose(_PlannerItem item) async {
    final scheduledAt = item.scheduledAt;
    if (scheduledAt == null) return;
    final dose =
        item.doseLog ??
        DoseLog(
          uuid: _uuid.v4(),
          protocolUuid: item.protocol.uuid,
          protocolPeptideUuid: item.peptide.uuid,
          peptideName: item.peptide.peptideName,
          scheduledAt: scheduledAt,
          amountTaken: item.schedule.dosePerInjection,
          units: item.schedule.doseUnit,
          syringeUnits: item.schedule.syringeUnits,
          blendSnapshot: item.schedule.blendVial,
        );
    HapticFeedback.lightImpact();
    await showModalBottomSheet<void>(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (_) => LogDoseSheet(dose: dose),
    );
    if (!mounted) return;
    final provider = context.read<DoseLogProvider>();
    setState(
      () => _doseLogs = <DoseLog>[...provider.recent30, ...provider.today],
    );
  }

  List<_WashoutItem> _washoutsForDate(DateTime date) {
    final result = <_WashoutItem>[];
    for (final protocol in widget.protocols) {
      if (protocol.status != ProtocolStatus.active) continue;
      for (var index = 0; index < protocol.peptides.length; index++) {
        final peptide = protocol.peptides[index];
        if (!peptide.isInWashout(
          protocolStart: protocol.startDate,
          date: date,
        )) {
          continue;
        }
        result.add(
          _WashoutItem(
            protocol: protocol,
            peptide: peptide,
            colorHex: peptide.labelColorHex.isEmpty
                ? defaultPeptideLabelColorHex(index)
                : peptide.labelColorHex,
          ),
        );
      }
    }
    return result;
  }

  void _moveWeek(int delta) {
    HapticFeedback.selectionClick();
    setState(() {
      _weekStart = _weekStart.add(Duration(days: 7 * delta));
      _selectedDate = _weekStart;
    });
  }

  void _jumpToToday() {
    HapticFeedback.selectionClick();
    final today = _day(DateTime.now());
    setState(() {
      _selectedDate = today;
      _weekStart = _mondayOf(today);
    });
  }
}

